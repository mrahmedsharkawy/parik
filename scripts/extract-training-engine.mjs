// Mechanical extraction: bot-training.html remains the trained source of truth.
// No intent, matching, pricing or conversation rules belong in this generator.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
export function trainingSource() {
  const html = readFileSync(new URL('bot-training.html', root), 'utf8');
  const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
  const source = scripts.find(x => x[1].includes('async function processBotMessageCore('))?.[1];
  if (!source) throw new Error('Trained engine script not found');
  const end = source.indexOf('let __botProcessingPromiseV7=null;');
  if (end < 0) throw new Error('Training bootstrap boundary changed; review extraction');
  return source.slice(0, end);
}
export function generatedSource() {
  const source = trainingSource();
  const boundary = readFileSync(new URL('supabase/functions/_shared/training-boundary.inc', root), 'utf8');
  const sha = createHash('sha256').update(source).update('\n--BOUNDARY--\n').update(boundary).digest('hex');
  return `// GENERATED by scripts/extract-training-engine.mjs. DO NOT EDIT.\n// Source SHA256: ${sha}\nimport { trainingEnvironment } from './training-environment.mjs';\nexport const BOT_ENGINE_VERSION = 'bariq-v57-${sha.slice(0,12)}';\nexport function createTrainingEngine(io = {}) {\nconst {window,document,localStorage,sessionStorage,location,history,fetch} = trainingEnvironment(io);\n${source}\n${boundary}\n}\n`;
}
if (process.argv[1] && new URL('file:///' + process.argv[1].replaceAll('\\', '/')).href === import.meta.url) {
  const target = new URL('supabase/functions/_shared/training-engine.generated.mjs', root);
  const generated = generatedSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== generated) throw new Error('Training engine is stale; run extraction');
  } else writeFileSync(target, generated);
}
