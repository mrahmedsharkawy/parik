function getFooterPagesJsonCandidates() {
  return [
    location.pathname
      .replace(/\/policy\/[^\/.]+$/, "/")
      .replace(/\/policy\.html$/, "/")
      .replace(/\/[^\/]*$/, "/") + "java/footer-pages.json",
    "./java/footer-pages.json",
    "/java/footer-pages.json",
  ];
}

async function loadFooterPagesJson() {
  let lastError = "";
  for (const jsonPath of getFooterPagesJsonCandidates()) {
    try {
      const res = await fetch(jsonPath, {
        cache: "no-store",
      });
      if (res.ok) return await res.json();
      lastError = `fetch(${jsonPath}) => ${res.status}`;
    } catch (err) {
      lastError = err.message;
    }
  }
  throw new Error("json not found: " + lastError);
}

function getFooterPageLang() {
  const urlLang = new URLSearchParams(location.search).get("lang");
  if ("en" === urlLang || "ar" === urlLang) return urlLang;
  const storedLang = localStorage.getItem("lang");
  if ("en" === storedLang || "ar" === storedLang) return storedLang;
  return "en" === document.documentElement.lang ? "en" : "ar";
}

